#!/usr/bin/env bash
# scripts/memory-export.sh
# Item #3 — exports the semantic memory layer (claude-mem MCP) into the
# git-versioned markdown audit trail at memory/. Runs nightly via cron, or on
# the Stop hook, or on demand.
#
# Contract: when claude-mem is configured, this script appends a dated section
# to memory/semantic_export.md with whatever the MCP returns for the project.
# When it is not configured, the script is a no-op (exits 0 with a notice).
#
# This is the "audit trail" half of the hybrid model:
#   Layer 1 (live):   claude-mem MCP, queried mid-session via /arib-memory-search
#   Layer 2 (audit):  memory/*.md, exported here, committed to git

set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
cd "${REPO_ROOT}"

EXPORT_FILE="memory/semantic_export.md"
TS="$(date -u +%Y-%m-%dT%H:%M:%SZ)"

# 1. Detect whether claude-mem is reachable. If not, no-op.
if [[ -z "${CLAUDE_MEM_API_KEY:-}" ]]; then
  echo "[memory-export] CLAUDE_MEM_API_KEY not set — skipping (no-op)."
  exit 0
fi

# 2. Probe the MCP. Real upstream tool name and CLI surface to be wired in once
# the MCP package is finalized. For now we stub the call behind a function so
# the contract is visible and the export file structure is preserved.
fetch_semantic_dump() {
  # Replace with: npx claude-mem export --project ccm --format markdown
  # When stubbed, emit a placeholder entry so the file structure is valid.
  if command -v claude-mem >/dev/null 2>&1; then
    claude-mem export --project "${CLAUDE_MEM_PROJECT:-ccm}" --format markdown 2>/dev/null \
      || echo "(claude-mem CLI failed — check CLAUDE_MEM_API_KEY and project name)"
  else
    echo "(claude-mem CLI not installed — install or set MCP up via .mcp.json)"
  fi
}

DUMP="$(fetch_semantic_dump)"

# 3. Append to export file. Prepend the date-stamped section header.
mkdir -p memory
if [[ ! -f "$EXPORT_FILE" ]]; then
  cat > "$EXPORT_FILE" <<'HEAD'
# Semantic Memory Export

This file is the markdown audit trail of the live semantic memory layer
(claude-mem MCP). It is regenerated by `scripts/memory-export.sh` and committed
to git so that long-horizon decisions and context remain reviewable in plain
text — not just retrievable via vector search.

Sections are appended chronologically. Old sections are not edited; if a
recorded fact is later proven wrong, add a new section that supersedes it.

---

HEAD
fi

{
  printf '\n## Export — %s\n\n' "$TS"
  printf '%s\n' "$DUMP"
} >> "$EXPORT_FILE"

echo "[memory-export] appended export to $EXPORT_FILE"
